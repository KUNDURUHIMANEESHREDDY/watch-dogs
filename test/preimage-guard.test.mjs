/* ------------------------------------------------------------------ *
 * The hash itself
 * ------------------------------------------------------------------ */

test('the hash distinguishes versions that share an anchor', () => {
  // This is the case the anchor check cannot see.
  const before = 'const MARKER = 1;\nmodule.exports = { MARKER };\n';
  const after = 'const MARKER = 1;\n// a build added this\nmodule.exports = { MARKER };\n';
  assert.ok(before.includes('const MARKER = 1;'));
  assert.ok(after.includes('const MARKER = 1;'), 'the anchor must be in both for this to mean anything');
  assert.notEqual(sha256Of(before), sha256Of(after));
});

test('the hash is stable for identical content', () => {
  assert.equal(sha256Of('same'), sha256Of('same'));
  assert.equal(sha256Of('a'), sha256Of(Buffer.from('a', 'utf8')));
  assert.notEqual(sha256Of('a'), sha256Of('b'));
});

test('shortHash is for messages only and is never compared', () => {
  const full = sha256Of('anything');
  assert.equal(full.length, 64);
  assert.equal(shortHash(full), full.slice(0, 12) + '...');
  // Two hashes sharing a 12-character prefix would compare equal in short form,
  // which is exactly why nothing compares short forms.
  assert.notEqual(shortHash(sha256Of('a')), shortHash(sha256Of('b')));
});

/* ------------------------------------------------------------------ *
 * Multiple files
 * ------------------------------------------------------------------ */

test('each file gets its own preimage, and one stale file does not block the other', async () => {
  const { root, checkArgv } = project();
  writeFileSync(join(root, 'src', 'b.js'), 'const OTHER = 1;\nmodule.exports = { OTHER };\n', 'utf8');

  const files = [
    { path: 'src/a.js', find: 'const MARKER = 1;', replace: 'const MARKER = 2;' },
    { path: 'src/b.js', find: 'const OTHER = 1;', replace: 'const OTHER = 2;' },
  ];
  const v = await verifyProposals({ projectRoot: root, files, verifyCfg: { command: checkArgv, timeoutMs: 60_000 } });
  assert.equal(v.verdict, 'pass', v.why);
  assert.equal(v.preimages.length, 2);
  assert.notEqual(v.preimages[0].sha256, v.preimages[1].sha256, 'two different files share a preimage');

  // Only the first file moves.
  writeFileSync(join(root, 'src', 'a.js'), 'const MARKER = 1;\n// moved\nmodule.exports = { MARKER };\n', 'utf8');

  const a = applierFor(root);
  const pre = new Map(v.preimages.map((p) => [p.path, p.sha256]));
  const r1 = a.apply({ kind: 'patch-file', ...files[0], expectPreimage: pre.get('src/a.js') }, { cwd: root, source: 'llm' });
  const r2 = a.apply({ kind: 'patch-file', ...files[1], expectPreimage: pre.get('src/b.js') }, { cwd: root, source: 'llm' });

  assert.equal(r1.status, 'stale', 'the changed file should have been refused');
  assert.equal(r2.status, 'applied', 'the unchanged file should still apply');
});

